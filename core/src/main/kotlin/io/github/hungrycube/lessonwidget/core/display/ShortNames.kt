    /** Сравнение без учёта регистра, «ё» и лишних пробелов. */
    private fun key(text: String) = text.lowercase().replace('ё', 'е').replace(Regex("""\s+"""), " ").trim()

    fun shorten(title: String): String =
        title.split(" / ").joinToString(" / ") { part ->
            val clean = part.replace(noise, " ").trim()
            known[key(clean)] ?: clean
        }
